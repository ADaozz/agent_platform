import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { chromium } from 'playwright'

const port = 4347
const base = process.env.MODEL_SETTINGS_BASE || `http://127.0.0.1:${port}`
const server = process.env.MODEL_SETTINGS_BASE ? null : spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', String(port), '--strictPort'], { cwd: new URL('..', import.meta.url), stdio: 'ignore' })
let browser
const mask = '__UNCHANGED_SECRET__'
const source = key => ({ base_url: 'https://example.com/v1', api: 'chat_completions', api_key: key, reasoning_efforts: ['high', 'low', 'max'], models: { 'fixture-model': { context_window: 1000 } } })
const config = models => ({ revision: 1, llm: { default: `${Object.keys(models)[0]}/fixture-model`, models }, profiles: [] })
try {
  for (let count = 0; !process.env.MODEL_SETTINGS_BASE && count < 100; count++) {
    try { if ((await fetch(base)).ok) break } catch {}
    await new Promise(resolve => setTimeout(resolve, 100))
  }
  browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || '/usr/bin/google-chrome', args: ['--no-sandbox'] })
  const page = await browser.newPage({ viewport: { width: 1360, height: 900 }, ignoreHTTPSErrors: true })
  page.setDefaultTimeout(10000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  let conflict = false
  let personal = config({ deepseek: source(mask), custom: source(mask) })
  let global = config({ deepseek: source(mask), qwen: source(mask) })
  const calls = []
  await page.route('**/api/**', async route => {
    const path = new URL(route.request().url()).pathname
    if (!path.startsWith('/api/')) return route.continue()
    const mine = path.endsWith('/models/personal')
    if (path.endsWith('/platform/capabilities')) return route.fulfill({ json: { revision: 1, editable: true, core_tools: Array.from({ length: 30 }, (_, i) => ({ name: 'tool' + i, enabled: true })), tools: [], skills: [] } })
    if (path.endsWith('/models/options')) return route.fulfill({ json: { default: '', profiles: [{ id: 'deepseek/fixture-model', model: 'fixture-model', scope: 'global', configured: true }], default_reasoning_effort: null } })
    if (path.endsWith('/models') || mine) {
      if (route.request().method() === 'PUT') {
        const body = route.request().postDataJSON()
        calls.push({ scope: mine ? 'personal' : 'global', ...body })
        if (conflict) return route.fulfill({ status: 409, json: { detail: '模型配置已更新，请重新打开后编辑' } })
        const previous = mine ? personal : global
        assert.equal(body.revision, previous.revision)
        const result = { revision: previous.revision + 1, llm: structuredClone(body.llm), profiles: [] }
        for (const item of Object.values(result.llm.models)) if (item.api_key) item.api_key = mask
        if (mine) personal = result
        else global = result
      }
      return route.fulfill({ json: mine ? personal : global })
    }
    return route.fulfill({ json: [] })
  })
  await page.addInitScript(() => {
    localStorage.setItem('itam_token', 'fixture')
    localStorage.setItem('itam_user', JSON.stringify({ username: 'fixture', roles: [{ label: 'admin' }], permissions: [] }))
    localStorage.setItem('itam-locale', 'en')
    localStorage.setItem('itam-theme', 'light')
  })
  await page.goto(`${base}/settings/models`, { waitUntil: 'domcontentloaded' })
  const registry = page.locator('.registry-panel')
  await registry.waitFor()
  const dialog = page.getByRole('dialog')
  const addButton = page.locator('.page-head').getByRole('button', { name: 'Add model', exact: true })
  const close = async () => { await dialog.locator('.modal-close').click(); await dialog.waitFor({ state: 'hidden' }) }
  const add = async provider => {
    await addButton.click()
    await dialog.locator(`[data-provider="${provider}"]`).click()
  }
  const edit = async (provider, scope) => {
    await registry.getByRole('combobox', { name: 'Filter by scope' }).selectOption(scope)
    await registry.getByRole('textbox', { name: 'Search models or providers' }).fill(provider)
    await registry.locator('tbody tr').first().getByRole('button', { name: 'Edit', exact: true }).click()
  }
  assert.equal(await registry.locator('tbody tr').count(), 4, 'Only saved models are listed initially')
  assert.equal(await page.locator('.provider-sidebar, .management-tabs').count(), 0)
  assert.equal(await dialog.count(), 0)
  assert.equal(await page.locator('.page-head-emblem').count(), 1)
  assert.equal(await page.getByRole('link', { name: 'View usage', exact: true }).count(), 0)
  await addButton.click()
  assert(await dialog.locator('[data-provider="deepseek"]').isDisabled(), 'Already configured in both scopes')
  const icons = dialog.locator('.provider-choice img')
  assert.equal(await icons.count(), 3)
  assert(await icons.evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0)))
  await dialog.locator('[data-provider="qwen"]').click()
  await dialog.locator('input[type=password]').fill('unsaved-qwen')
  await close()
  await add('custom')
  await dialog.getByPlaceholder('e.g. openai').fill('draft-custom')
  await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await dialog.getByRole('alert').waitFor()
  assert.match(await dialog.getByRole('alert').innerText(), /Enter an API key/)
  await close()
  await edit('deepseek', 'personal')
  assert.equal(await dialog.locator('input[type=password]').inputValue(), '')
  assert.equal(await dialog.locator('.save-target').count(), 0, 'Existing scope is fixed')
  assert.equal(await dialog.getByText('Endpoint URL', { exact: true }).count(), 0)
  assert.equal(await dialog.locator('.model-search, .preset-model-row, .source-fields details').count(), 0, 'Official config is a compact form')
  assert.equal(await dialog.locator('.preset-model-name').count(), 1)
  await page.waitForFunction(() => getComputedStyle(document.querySelector('[role=dialog]').closest('.modal-scrim')).opacity === '1')
  await page.screenshot({ path: '/tmp/model-settings-compact-editor.png', animations: 'disabled' })
  await dialog.locator('input[type=password]').fill('new-personal')
  await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(calls.length, 1)
  assert.equal(calls[0].scope, 'personal')
  assert.equal(calls[0].llm.models.qwen, undefined)
  assert.equal(calls[0].llm.models['draft-custom'], undefined)
  assert.equal(calls[0].llm.models.custom.api_key, mask)
  await add('qwen')
  assert.equal(await dialog.locator('input[type=password]').inputValue(), 'unsaved-qwen')
  await close()
  await edit('deepseek', 'global')
  await dialog.locator('input[type=password]').fill('new-global')
  await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await dialog.getByRole('heading', { name: 'Save global configuration', exact: true }).waitFor()
  assert.equal(calls.length, 1, 'No write before global confirmation')
  assert.equal(await page.getByRole('dialog').count(), 1, 'Confirmation uses one focus-trapped dialog')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  assert.equal(await dialog.locator('input[type=password]').inputValue(), 'new-global')
  await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await dialog.getByRole('button', { name: 'OK', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(calls.at(-1).scope, 'global')
  assert.equal(calls.at(-1).llm.models.qwen.api_key, mask)
  await add('glm')
  await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await dialog.getByRole('alert').waitFor()
  for (const language of ['zh', 'en']) {
    await close()
    if (await page.locator('html').getAttribute('lang') !== (language === 'zh' ? 'zh-CN' : 'en')) await page.locator('.topbar-locale').click()
    for (const theme of ['dark', 'light']) {
      if (await page.locator('html').getAttribute('data-theme') !== theme) await page.locator('.topbar-toggle').last().click()
      await page.locator('.page-head button').click()
      await dialog.locator('[data-provider="glm"]').click()
      assert.match(await dialog.getByRole('alert').innerText(), language === 'zh' ? /请填写/ : /Enter/)
      const picker = dialog.locator('.save-target select')
      await picker.click()
      assert(await picker.evaluate(el => el.matches(':open')))
      assert.equal(await picker.evaluate(el => getComputedStyle(el, '::picker(select)').paddingTop), '4px')
      await page.screenshot({ path: `/tmp/model-select-${language}-${theme}.png`, animations: 'disabled' })
      await page.keyboard.press('Escape')
      assert(await dialog.isVisible(), 'Escape closes the select popup before the dialog')
      await page.waitForFunction(() => document.querySelector('[role=dialog] .save-target select')?.matches(':open') === false)
      await close()
    }
    await page.locator('.page-head button').click()
    await dialog.locator('[data-provider="glm"]').click()
  }
  await close()
  conflict = true
  await edit('deepseek', 'personal')
  await dialog.locator('input[type=password]').fill('retry-key')
  await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await dialog.getByRole('alert').waitFor()
  assert.match(await dialog.getByRole('alert').innerText(), /Reload/)
  assert.equal(await dialog.locator('input[type=password]').inputValue(), 'retry-key')
  conflict = false
  await dialog.locator('input[type=password]').fill('')
  await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(calls.at(-1).llm.models.deepseek.api_key, mask)
  await add('qwen')
  await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(calls.at(-1).llm.models.qwen.api_key, 'unsaved-qwen')
  assert.equal(calls.at(-1).llm.models['draft-custom'], undefined)
  await add('glm')
  await dialog.locator('input[type=password]').fill('new-glm-global')
  await dialog.locator('.save-target select').selectOption('global')
  const countBefore = calls.length
  await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await dialog.getByRole('heading', { name: 'Save global configuration', exact: true }).waitFor()
  assert.equal(calls.length, countBefore)
  await dialog.getByRole('button', { name: 'OK', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(calls.at(-1).llm.models.glm.api_key, 'new-glm-global')
  await edit('custom', 'personal')
  assert.equal(await dialog.getByPlaceholder('low, medium, high').inputValue(), 'low, high, max')
  assert(await dialog.getByPlaceholder('e.g. openai').isDisabled())
  await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.deepEqual(calls.at(-1).llm.models.custom.reasoning_efforts, ['high', 'low', 'max'])
  await registry.getByRole('button', { name: 'Default settings', exact: true }).click()
  const personalSettings = dialog.locator('.settings-form[data-scope=personal]')
  await personalSettings.locator('select').selectOption('qwen/qwen3.8-flash')
  await personalSettings.getByRole('button', { name: 'Save settings', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(calls.at(-1).llm.default, 'qwen/qwen3.8-flash')
  await registry.getByRole('textbox', { name: 'Search models or providers' }).fill('glm')
  await registry.getByRole('combobox', { name: 'Filter by scope' }).selectOption('global')
  assert.equal(await registry.locator('tbody tr').count(), 4)
  await registry.getByRole('textbox', { name: 'Search models or providers' }).fill('')
  await registry.getByRole('combobox', { name: 'Filter by scope' }).selectOption('all')
  await page.waitForFunction(() => !document.querySelector('.toast-card'))
  await page.screenshot({ path: '/tmp/model-settings-simplified.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.evaluate(() => { document.querySelector('main').scrollTop = 300 })
  const maskCoversTop = await page.locator('.page-head-sticky').evaluate(el => el.getBoundingClientRect().top + parseFloat(getComputedStyle(el, '::before').top) <= document.querySelector('main').getBoundingClientRect().top)
  assert(maskCoversTop)
  await page.screenshot({ path: '/tmp/model-settings-mobile.png', animations: 'disabled' })
  await addButton.click()
  await dialog.waitFor()
  await page.waitForFunction(() => getComputedStyle(document.querySelector('[role=dialog]').closest('.modal-scrim')).opacity === '1')
  await page.screenshot({ path: '/tmp/model-settings-chooser-mobile.png', animations: 'disabled' })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await close()
  await page.goto(`${base}/settings/capabilities`, { waitUntil: 'domcontentloaded' })
  await page.locator('.page-head-disc').waitFor()
  if (await page.locator('html').getAttribute('lang') !== 'zh-CN') await page.locator('.topbar-locale').click()
  await page.screenshot({ path: '/tmp/shared-header-mobile.png', animations: 'disabled' })
  const userPage = await browser.newPage({ ignoreHTTPSErrors: true })
  await userPage.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname
    if (!path.startsWith('/api/')) return route.continue()
    if (path.endsWith('/models/personal')) return route.fulfill({ json: personal })
    if (path.endsWith('/models/options')) return route.fulfill({ json: { profiles: [{ id: 'deepseek/global-model', model: 'global-model', scope: 'global', context_window: 1000000, reasoning_efforts: ['max', 'low', 'high'] }], default: '' } })
    assert(!path.endsWith('/models'), 'Non-admin must not read global credentials')
    return route.fulfill({ json: [] })
  })
  await userPage.addInitScript(() => {
    localStorage.setItem('itam_token', 'user')
    localStorage.setItem('itam_user', JSON.stringify({ username: 'user', roles: [], permissions: [] }))
    localStorage.setItem('itam-locale', 'en')
  })
  await userPage.goto(`${base}/settings/models`, { waitUntil: 'domcontentloaded' })
  const userRegistry = userPage.locator('.registry-panel')
  await userRegistry.waitFor()
  await userRegistry.getByRole('combobox', { name: 'Filter by scope' }).selectOption('global')
  const globalRow = userRegistry.locator('tbody tr').first()
  assert.equal(await globalRow.getByRole('button').count(), 0)
  await globalRow.getByText('Read only', { exact: true }).waitFor()
  await userPage.locator('.page-head button').click()
  await userPage.getByRole('dialog').locator('[data-provider="glm"]').click()
  const personalOnly = userPage.getByRole('dialog').locator('.save-target select')
  assert.equal(await personalOnly.locator('option').count(), 1)
  assert.equal(await personalOnly.inputValue(), 'personal')
  assert.deepEqual(errors, [])
  console.log('Model settings: configured-first list, add/edit dialogs, local brand icons, scope isolation, confirmations, validation, themes, i18n, mobile and permissions passed.')

} finally {
  await browser?.close()
  server?.kill('SIGTERM')
}
